QuickSpellPanel::QuickSpellPanel(BattleInterface & owner)
	: CIntObject(0)
	, owner(owner)
{
	OBJECT_CONSTRUCTION;

	addUsedEvents(LCLICK | SHOW_POPUP | MOVE | INPUT_MODE_CHANGE);

	jadeTheme = JsonNode(JsonPath::builtin("config/widgets/BattleWindow2.json"))["jadeTheme"].Bool();
	horizontal = jadeTheme && ENGINE->screenDimensions().y >= 720;
	pos = horizontal ? Rect(0, 0, 800, 60) : Rect(0, 0, 52, 600);
	background = std::make_shared<CFilledTexture>(ImagePath::builtin(jadeTheme ? "cultivation/ui/jade/texture" : "DIBOXBCK"), pos);
	rect = std::make_shared<TransparentFilledRectangle>(Rect(0, 0, pos.w + 1, pos.h + 1), ColorRGBA(0, 0, 0, 0), jadeTheme ? ColorRGBA(201, 205, 190, 0) : ColorRGBA(241, 216, 120, 255));

	create();
}

std::vector<std::tuple<SpellID, bool>> QuickSpellPanel::getSpells() const
{
	std::vector<SpellID> spellIds;
	std::vector<bool> spellIdsFromSetting;
	for(int i = 0; i < QUICKSPELL_SLOTS; i++)
	{
		std::string spellIdentifier = persistentStorage["quickSpell"][std::to_string(i)].String();
		SpellID id;
		try
		{
			id = SpellID::decode(spellIdentifier);
		}
		catch(const IdentifierResolutionException &)
		{
			id = SpellID::NONE;
		}
		spellIds.push_back(id);
		spellIdsFromSetting.push_back(id != SpellID::NONE);
	}

	// autofill empty slots with spells if possible
	const auto * hero = owner.getBattle()->battleGetMyHero();
	for(int i = 0; i < QUICKSPELL_SLOTS; i++)
	{
		if(spellIds[i] != SpellID::NONE)
			continue;

		for(const auto & availableSpellID : LIBRARY->spellh->getDefaultAllowed())
		{
			const auto * availableSpell = availableSpellID.toSpell();
			if(!availableSpell->isAdventure() && !availableSpell->isCreatureAbility() && hero->canCastThisSpell(availableSpell) && !vstd::contains(spellIds, availableSpell->getId()))
			{
				spellIds[i] = availableSpell->getId();
				break;
			}
		}
	}

	std::vector<std::tuple<SpellID, bool>> ret;
	for(int i = 0; i < QUICKSPELL_SLOTS; i++)
		ret.push_back(std::make_tuple(spellIds[i], spellIdsFromSetting[i]));
	return ret;
}

void QuickSpellPanel::create()
{
	OBJECT_CONSTRUCTION;

	labels.clear();
	buttons.clear();
	buttonsDisabled.clear();
	buttonsIsAutoGenerated.clear();

	const auto * hero = owner.getBattle()->battleGetMyHero();
	if(!hero)
	{
		redraw();
		return;
	}

	auto spells = getSpells();
	if(horizontal)
	{
		labels.push_back(std::make_shared<CLabel>(48, 25, EFonts::FONT_MEDIUM, ETextAlignment::CENTER, ColorRGBA(243, 240, 231), LIBRARY->generaltexth->translate("cultivation.battle.skills")));
		labels.push_back(std::make_shared<CLabel>(750, 25, EFonts::FONT_TINY, ETextAlignment::CENTER, ColorRGBA(154, 176, 161), LIBRARY->generaltexth->translate("cultivation.battle.skillsHint")));
	}
	for(int i = 0; i < QUICKSPELL_SLOTS; i++)
	{
		SpellID id;
		const Point slot = horizontal ? Point(100 + 50 * i, 2) : Point(2, 7 + 50 * i);
		bool fromSettings;
		std::tie(id, fromSettings) = spells[i];

		std::string hoverText;
		if(id.hasValue())
		{
			MetaString tooltip;
			tooltip.appendTextID("core.genrltxt.26");
			tooltip.replaceName(id);
			hoverText = tooltip.toString(&GAME->translator());
		}
		else
			hoverText = LIBRARY->generaltexth->translate("vcmi.battleWindow.quickSpell.emptySlot");

		const auto & callback = [this, id, hero]()
		{
			if(id.hasValue() && id.toSpell()->canBeCast(owner.getBattle().get(), spells::Mode::HERO, hero))
				owner.castThisSpell(id);
		};

		auto button = std::make_shared<CButton>(slot, AnimationPath::builtin(jadeTheme ? "cultivation/ui/jade/skill" : "spellint"), CButton::tooltip(hoverText), callback);
		if(!jadeTheme || id != SpellID::NONE)
			button->setOverlay(std::make_shared<CAnimImage>(AnimationPath::builtin("spellint"), id != SpellID::NONE ? id.num + 1 : 0));
		button->addPopupCallback([this, i, hero](){
			ENGINE->input().hapticFeedback();
			ENGINE->windows().createAndPushWindow<CSpellWindow>(hero, owner.curInt.get(), true, [i](SpellID spell){ changeSelectedSpell(i, spell); });
		});

		if(fromSettings)
			buttonsIsAutoGenerated.push_back(std::make_shared<TransparentFilledRectangle>(Rect(slot.x + 43, slot.y + 30, 4, 4), jadeTheme ? ColorRGBA(154, 176, 161) : Colors::ORANGE));

		if(!id.hasValue() || !id.toSpell()->canBeCast(owner.getBattle().get(), spells::Mode::HERO, hero))
		{
			buttonsDisabled.push_back(std::make_shared<TransparentFilledRectangle>(Rect(slot.x, slot.y, 48, jadeTheme ? 40 : 36), jadeTheme ? ColorRGBA(16, 22, 22, 145) : ColorRGBA(7, 18, 20, 172)));
		}
		if(ENGINE->input().getCurrentInputMode() == InputMode::KEYBOARD_AND_MOUSE)
			labels.push_back(std::make_shared<CLabel>(slot.x + 5, slot.y + 3, EFonts::FONT_TINY, ETextAlignment::TOPLEFT, jadeTheme ? ColorRGBA(243, 240, 231) : Colors::WHITE, keyBindingsConfig["keyboard"]["battleSpellShortcut" + std::to_string(i)].String()));

		if(horizontal && id.hasValue())
			labels.push_back(std::make_shared<CLabel>(slot.x + 24, slot.y + 49, EFonts::FONT_CALLI, ETextAlignment::CENTER, ColorRGBA(243, 240, 231), id.toSpell()->getNameTranslated(), 48));

		buttons.push_back(button);
	}

	redraw();
}

void QuickSpellPanel::changeSelectedSpell(int i, SpellID spell)
{
	//NOTE: this is static method - since QuickSpellPanel can be re-created while spellbook is open breaking any pointers!
	Settings configID = persistentStorage.write["quickSpell"][std::to_string(i)];
	configID->String() = spell == SpellID::NONE ? "" : spell.toSpell()->identifier;

	for (auto battleWindow : ENGINE->windows().findWindows<BattleWindow>())
		battleWindow->updateQueue(); // also recreates quick spell panel, if exists
}

void QuickSpellPanel::show(Canvas & to)
{
	// the battlefield erases its own area every frame, so only a panel above it must repaint
	if(owner.fieldController && pos.intersectionTest(owner.fieldController->pos))
		showAll(to);
	CIntObject::show(to);
}

void QuickSpellPanel::inputModeChanged(InputMode modi)
{
	create();
	redraw();
}
